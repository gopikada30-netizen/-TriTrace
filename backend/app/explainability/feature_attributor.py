"""
Interpretable feature attribution for TriTrace multi-signal features.
Categorizes structural and stylistic signals into readable radar/bar metrics
with quantitative evidence of AI vs Human indicators.
"""

from typing import Dict, List, Any


class MultiSignalFeatureAttributor:
    """Interprets and explains handcrafted code signals."""

    CATEGORIES = {
        "Lexical Diversity": ["type_token_ratio", "shannon_entropy", "mean_identifier_length", "std_identifier_length"],
        "Repetition & Regularity": ["bigram_repetition", "trigram_repetition", "line_repetition_rate", "std_tokens_per_line"],
        "Formatting & Layout": ["mean_line_length", "std_line_length", "max_line_length", "blank_line_ratio", "dominant_naming_style_ratio"],
        "Syntactic Complexity": ["ast_max_depth", "ast_branch_density", "max_nesting_depth", "ast_control_flow_count"],
        "Documentation & Style": ["comment_ratio", "inline_comment_density", "ast_comprehension_ratio"]
    }

    # Reference baselines derived from typical human vs AI corpora
    AI_BASELINES = {
        "type_token_ratio": 0.42,
        "shannon_entropy": 4.60,
        "bigram_repetition": 0.38,
        "dominant_naming_style_ratio": 0.95,
        "comment_ratio": 0.18,
        "ast_max_depth": 6.5,
        "std_line_length": 14.5
    }

    HUMAN_BASELINES = {
        "type_token_ratio": 0.58,
        "shannon_entropy": 5.25,
        "bigram_repetition": 0.22,
        "dominant_naming_style_ratio": 0.78,
        "comment_ratio": 0.08,
        "ast_max_depth": 8.2,
        "std_line_length": 22.0
    }

    def attribute(self, features: Dict[str, float], predicted_class: str) -> Dict[str, Any]:
        """Generate categorized attribution breakdown and human-readable explanations."""
        breakdown = []
        category_scores: Dict[str, float] = {}

        for cat_name, feat_keys in self.CATEGORIES.items():
            cat_sum = 0.0
            cat_count = 0
            signals = []

            for key in feat_keys:
                val = float(features.get(key, 0.0))
                # Normalized contribution score (0 to 1)
                ai_ref = self.AI_BASELINES.get(key, 0.5)
                human_ref = self.HUMAN_BASELINES.get(key, 0.5)
                
                # Signal direction: positive -> aligns more with AI pattern, negative -> aligns more with human pattern
                diff = abs(ai_ref - human_ref)
                if diff > 1e-4:
                    signal_strength = (val - human_ref) / diff
                    signal_strength = max(-1.0, min(1.0, signal_strength))
                else:
                    signal_strength = 0.0

                signals.append({
                    "name": key.replace("_", " ").title(),
                    "key": key,
                    "value": round(val, 3),
                    "ai_baseline": round(ai_ref, 3),
                    "human_baseline": round(human_ref, 3),
                    "signal_alignment": "AI-leaning" if signal_strength > 0.1 else ("Human-leaning" if signal_strength < -0.1 else "Neutral"),
                    "score": round(abs(signal_strength), 3)
                })
                cat_sum += abs(signal_strength)
                cat_count += 1

            avg_cat_score = cat_sum / max(1, cat_count)
            category_scores[cat_name] = round(avg_cat_score, 3)
            breakdown.append({
                "category": cat_name,
                "importance": round(avg_cat_score, 3),
                "signals": signals
            })

        # Generate summary findings
        key_findings = []
        ttr = features.get("type_token_ratio", 0.5)
        if ttr < 0.45:
            key_findings.append("Low type-token diversity indicating repetitive vocabulary typical of LLM autocomplete loops.")
        else:
            key_findings.append("Elevated token diversity indicating varied variable naming characteristic of human developers.")

        rep = features.get("bigram_repetition", 0.25)
        if rep > 0.35:
            key_findings.append("Elevated n-gram repetition patterns across consecutive statement blocks.")

        comment_ratio = features.get("comment_ratio", 0.1)
        if comment_ratio > 0.20:
            key_findings.append("Extensive explanatory commenting and docstring density frequently generated by instruction-tuned models.")
        elif comment_ratio < 0.05:
            key_findings.append("Sparse comment presence and informal code flow typical of quick human authoring.")

        style_ratio = features.get("dominant_naming_style_ratio", 0.8)
        if style_ratio > 0.92:
            key_findings.append("Strict syntactic uniformity and rigid casing adherence throughout the snippet.")

        return {
            "categories": breakdown,
            "category_scores": category_scores,
            "key_findings": key_findings,
            "interpretation_notice": (
                "Feature attributions reflect statistical correlation with training corpora and do not constitute "
                "forensic proof of authorship. Developer editing or standardized templates can produce overlapping signatures."
            )
        }
