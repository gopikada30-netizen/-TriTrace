"""
API Router for Research History and Forensic Report Export.
"""

import json
from fastapi import APIRouter, HTTPException, Query, Response
from fastapi.responses import HTMLResponse
from typing import Optional, List, Dict, Any
from ..database.history_db import HistoryDatabase

router = APIRouter(prefix="/api/history", tags=["Research History"])
history_db = HistoryDatabase.get_instance()


@router.get("", response_model=List[Dict[str, Any]])
async def get_analysis_history(
    limit: int = Query(50, ge=1, le=200),
    offset: int = Query(0, ge=0),
    status: Optional[str] = Query(None, description="Filter by status: human, ai, uncertain, or all")
):
    """Retrieve telemetry of past code analyses."""
    return history_db.get_records(limit=limit, offset=offset, status_filter=status)


@router.get("/{record_id}", response_model=Dict[str, Any])
async def get_history_detail(record_id: str):
    """Retrieve full detail of an analysis run."""
    record = history_db.get_record_by_id(record_id)
    if not record:
        raise HTTPException(status_code=404, detail=f"History record '{record_id}' not found.")
    return record


@router.delete("/{record_id}")
async def delete_history_record(record_id: str):
    """Delete a single history record."""
    success = history_db.delete_record(record_id)
    if not success:
        raise HTTPException(status_code=404, detail="Record not found or already deleted.")
    return {"status": "success", "deleted_id": record_id}


@router.post("/clear")
async def clear_all_history():
    """Clear all history records."""
    history_db.clear_all()
    return {"status": "success", "message": "History cleared successfully."}


@router.get("/{record_id}/export/json")
async def export_report_json(record_id: str):
    """Export single analysis run as a standardized JSON forensic report."""
    record = history_db.get_record_by_id(record_id)
    if not record:
        raise HTTPException(status_code=404, detail="Record not found.")

    payload = {
        "report_type": "TriTrace Code Authorship Forensic Report",
        "record_id": record["id"],
        "timestamp": record["timestamp"],
        "metadata": {
            "language": record["language"],
            "code_lines": record["code_length_lines"],
            "token_count": record["token_count"],
            "model_version": record["model_version"]
        },
        "verdict": {
            "predicted_class": record["predicted_class"],
            "status": record["status"],
            "confidence": record["confidence"],
            "p_human": record["p_human"],
            "p_ai": record["p_ai"],
            "entropy": record["entropy"],
            "threshold_used": record["threshold_used"]
        },
        "codedna_profile": record.get("codedna", {}),
        "source_code": record["code_snippet"],
        "notice": (
            "This report is generated by the TriTrace Multi-Signal Authorship Attribution system. "
            "Estimates are probabilistic and indicate stylistic affinity rather than judicial proof."
        )
    }

    json_str = json.dumps(payload, indent=2)
    return Response(
        content=json_str,
        media_type="application/json",
        headers={"Content-Disposition": f"attachment; filename=tritrace_report_{record_id[:8]}.json"}
    )


